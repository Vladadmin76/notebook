// Проверка в браузере с касаниями (нужны npm run dev и playwright). Запуск: npm run check:maps
const { chromium } = require('playwright');
const { readFileSync } = require('fs');
const { createHmac } = require('crypto');
const env = Object.fromEntries(readFileSync(require('path').join(__dirname,'../../.dev.vars'),'utf8').split('\n').filter(l=>l.includes('=')).map(l=>[l.slice(0,l.indexOf('=')),l.slice(l.indexOf('=')+1)]));
const p = new URLSearchParams({ auth_date: String(Math.floor(Date.now()/1000)), user: JSON.stringify({ id: Number(env.ADMIN_TELEGRAM_ID), first_name: 'A' }) });
const dcs = [...p.entries()].map(([k,v])=>`${k}=${v}`).sort().join('\n');
p.set('hash', createHmac('sha256', createHmac('sha256','WebAppData').update(env.TG_BOT_TOKEN).digest()).update(dcs).digest('hex'));
const initData = p.toString();
const OUT = require('os').tmpdir() + '/';
(async () => {
  const b = await chromium.launch();
  const ctx = await b.newContext({ viewport: { width: 700, height: 800 }, hasTouch: true, isMobile: true, deviceScaleFactor: 1 });
  const page = await ctx.newPage();
  page.on('pageerror', e => console.log('PAGEERROR', e.message));
  page.on('console', m => { if (m.type()==='error') console.log('CONSOLE', m.text()); });
  await page.route('https://telegram.org/**', r => r.abort());
  await page.addInitScript((d) => { window.Telegram = { WebApp: { initData: d, initDataUnsafe: {}, ready(){}, expand(){}, colorScheme:'light', onEvent(){}, BackButton:{show(){},hide(){},onClick(){}}, showConfirm:(t,cb)=>cb(true), showAlert(){} } }; }, initData);
  await page.goto('http://localhost:8787/');
  await page.waitForSelector('[data-tab="maps"]'); await page.tap('[data-tab="maps"]');
  await page.waitForSelector('#newMap'); await page.tap('#newMap');
  await page.tap('#kBoard'); await page.waitForSelector('#mapPlusB'); await page.tap('#mapPlusB');
  await page.fill('#askIn','Идея'); await page.tap('#askYes'); await page.waitForSelector('.bnode');
  const T = (t) => '.bnode:text-is("' + t + '")';
  const add = async (parent, text) => { await page.tap(T(parent)); await page.tap('#bChild'); await page.fill('#askIn', text); await page.tap('#askYes'); await page.waitForTimeout(250); };
  await add('Идея','Машины'); await add('Идея','Колёса'); await add('Машины','Сборка'); await add('Колёса','Покупка');
  const cdp = await ctx.newCDPSession(page);
  const ctr = async (sel) => { const r = await page.locator(sel).first().boundingBox(); return {x:r.x+r.width/2,y:r.y+r.height/2}; };
  const tp = (type,x,y) => cdp.send('Input.dispatchTouchEvent',{type,touchPoints:type==='touchEnd'?[]:[{x,y,id:1}]});
  const dragTo = async (a, b) => { await tp('touchStart',a.x,a.y); for(let i=1;i<=12;i++){ await tp('touchMove',a.x+(b.x-a.x)*i/12,a.y+(b.y-a.y)*i/12); await page.waitForTimeout(25);} await tp('touchEnd'); await page.waitForTimeout(400); };
  const state = () => page.evaluate(async (d) => { const l=(await (await fetch('/api/maps',{headers:{Authorization:'tma '+d}})).json()).maps; const g=await (await fetch('/api/maps/get?id='+l[0].id,{headers:{Authorization:'tma '+d}})).json(); return {kind:g.kind,data:g.data}; }, initData);
  const pos = (t) => page.evaluate((t)=>{const e=[...document.querySelectorAll('.bnode')].find(x=>x.textContent===t);return e&&[parseInt(e.style.left),parseInt(e.style.top)];}, t);
  await page.screenshot({ path: OUT+'b1.png' });
  const p0 = await pos('Колёса'); const c1 = await ctr(T('Колёса'));
  await dragTo(c1, {x:c1.x, y:c1.y+120}); const p1 = await pos('Колёса');
  console.log('MOVE', JSON.stringify(p0), '->', JSON.stringify(p1));
  await dragTo(await ctr(T('Покупка')), await ctr(T('Сборка')));
  await page.fill('#askIn','Колёса на машине'); await page.tap('#askYes'); await page.waitForTimeout(400);
  await page.screenshot({ path: OUT+'b2.png' });
  await page.waitForTimeout(900);
  let st = await state();
  console.log('MERGE nodes', st.data.nodes.length, 'edges', JSON.stringify(st.data.edges.map(e=>[st.data.nodes.find(n=>n.id===e.from)?.topic, st.data.nodes.find(n=>n.id===e.to)?.topic])));
  const first = await page.evaluate(()=>{const g=document.querySelector('.bedge');return [g.dataset.from,g.dataset.to];});
  const mid = await ctr('.bedge[data-from="'+first[0]+'"][data-to="'+first[1]+'"] .hit');
  console.log('EDGE-MID', JSON.stringify(mid), await page.evaluate(([x,y])=>{const e=document.elementFromPoint(x,y);return e&&(e.tagName+'.'+e.getAttribute('class'));}, [mid.x,mid.y]));
  await tp('touchStart',mid.x,mid.y); await page.waitForTimeout(800); console.log('MODAL?', await page.evaluate(()=>document.querySelector('.modal')?.innerHTML.slice(0,80))); await page.screenshot({path:OUT+'b3a.png'}); await tp('touchEnd'); await page.waitForTimeout(650);
  await page.waitForSelector('#eIns'); await page.tap('#eIns'); await page.fill('#askIn','Вставка'); await page.tap('#askYes'); await page.waitForTimeout(400);
  await page.screenshot({ path: OUT+'b3.png' });
  await page.waitForTimeout(1000); st = await state();
  console.log('INSERT nodes', st.data.nodes.length, 'edges', st.data.edges.length);
  await page.tap('#bUndo'); await page.waitForTimeout(1200); st = await state();
  console.log('UNDO nodes', st.data.nodes.length);
  // разворот стрелки
  const e0 = await page.evaluate(()=>{const g=document.querySelector('.bedge');return [g.dataset.from,g.dataset.to];});
  const m0 = await ctr('.bedge[data-from="'+e0[0]+'"][data-to="'+e0[1]+'"] .hit');
  await tp('touchStart',m0.x,m0.y); await page.waitForTimeout(800); await tp('touchEnd'); await page.waitForTimeout(650);
  await page.waitForSelector('#eRev'); await page.tap('#eRev'); await page.waitForTimeout(1200);
  st = await state();
  console.log('REVERSE', JSON.stringify(st.data.edges.some(e=>e.from===e0[1]&&e.to===e0[0])), 'no old', JSON.stringify(!st.data.edges.some(e=>e.from===e0[0]&&e.to===e0[1])), 'edges', st.data.edges.length);
  // склейка связанных окошек теперь разрешена; пара «туда и обратно» не возникает
  const idea = await ctr(T('Идея')); const kid = await ctr(T('Машины'));
  await dragTo(idea, kid); await page.waitForTimeout(300);
  console.log('CONNECTED MERGE asks text:', await page.evaluate(()=>!!document.getElementById('askIn')));
  await page.fill('#askIn','Слитое'); await page.tap('#askYes'); await page.waitForTimeout(1300);
  st = await state();
  const pairs = st.data.edges.filter(e => st.data.edges.some(f => f.from===e.to && f.to===e.from)).length;
  console.log('AFTER nodes', st.data.nodes.length, 'edges', st.data.edges.length, 'mutual pairs', pairs, 'self-loops', st.data.edges.filter(e=>e.from===e.to).length);
  await page.tap('#backBtn'); await page.waitForSelector('[data-map]'); await page.tap('[data-map]'); await page.waitForSelector('.bnode'); await page.waitForTimeout(500);
  console.log('REOPEN nodes', await page.evaluate(()=>document.querySelectorAll('.bnode').length), 'edges', await page.evaluate(()=>document.querySelectorAll('.bedge').length));
  await page.screenshot({ path: OUT+'b4.png' });
  await b.close();
})();
