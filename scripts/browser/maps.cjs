// Проверка в браузере с касаниями (нужны npm run dev и playwright). Запуск: npm run check:maps
const { chromium } = require('playwright');
const { readFileSync } = require('fs');
const { createHmac } = require('crypto');
const env = Object.fromEntries(readFileSync(require('path').join(__dirname,'../../.dev.vars'),'utf8').split('\n').filter(l=>l.includes('=')).map(l=>[l.slice(0,l.indexOf('=')),l.slice(l.indexOf('=')+1)]));
const p = new URLSearchParams({ auth_date: String(Math.floor(Date.now()/1000)), user: JSON.stringify({ id: Number(env.ADMIN_TELEGRAM_ID), first_name: 'A' }) });
const dcs = [...p.entries()].map(([k,v])=>`${k}=${v}`).sort().join('\n');
p.set('hash', createHmac('sha256', createHmac('sha256','WebAppData').update(env.TG_BOT_TOKEN).digest()).update(dcs).digest('hex'));
const initData = p.toString();
const OUT = require('os').tmpdir() + '/';
(async () => {
  const b = await chromium.launch();
  const ctx = await b.newContext({ viewport: { width: 390, height: 800 }, hasTouch: true, isMobile: true, deviceScaleFactor: 1 });
  const page = await ctx.newPage();
  page.on('pageerror', e => console.log('PAGEERROR', e.message));
  page.on('console', m => { if (m.type()==='error') console.log('CONSOLE', m.text()); });
  await page.route('https://telegram.org/**', r => r.abort());
  await page.addInitScript((d) => { window.Telegram = { WebApp: { initData: d, initDataUnsafe: {}, ready(){}, expand(){}, colorScheme:'light', onEvent(){}, BackButton:{show(){},hide(){},onClick(){}}, showConfirm:(t,cb)=>cb(true), showAlert(){} } }; }, initData);
  await page.goto('http://localhost:8787/');
  await page.waitForSelector('[data-tab="maps"]');
  await page.tap('[data-tab="maps"]');
  await page.waitForSelector('#newMap'); await page.tap('#newMap'); await page.tap('#kTree');
  await page.waitForSelector('#mapPlus'); await page.screenshot({ path: OUT+'m1.png' });
  await page.tap('#mapPlus');
  await page.fill('#askIn','Переезд'); await page.tap('#askYes');
  await page.waitForSelector('me-root me-tpc');
  await page.tap('#mapChild'); await page.fill('#askIn','Документы'); await page.tap('#askYes');
  await page.waitForTimeout(300);
  // выбрать «Документы» и закрасить красным
  await page.tap('me-tpc:has-text("Документы")');
  await page.tap('#mapColor'); await page.tap('.sw[data-c="#e5484d"]');
  await page.waitForTimeout(300);
  await page.tap('#mapChild'); await page.fill('#askIn','Паспорт'); await page.tap('#askYes');
  await page.waitForTimeout(1200);
  await page.tap('#mapUndo'); await page.waitForTimeout(500); console.log('AFTER UNDO nodes', await page.evaluate(()=>document.querySelectorAll('me-tpc').length)); await page.tap('#mapRedo'); await page.waitForTimeout(500);
  await page.screenshot({ path: OUT+'m2a.png' });
  await page.tap('#mapFit'); await page.waitForTimeout(600);
  console.log(JSON.stringify(await page.evaluate(()=>['#mapbox','.map-container','me-nodes','me-root','.topbar'].map(q=>{const e=document.querySelector(q);const r=e&&e.getBoundingClientRect();return [q,r&&[r.x,r.y,r.width,r.height].map(Math.round)];}))));
  await page.screenshot({ path: OUT+'m2.png' });
  const saved = await page.evaluate(async (d) => { const r = await fetch('/api/maps',{headers:{Authorization:'tma '+d}}); const l=(await r.json()).maps; const g = await fetch('/api/maps/get?id='+l[0].id,{headers:{Authorization:'tma '+d}}); return {l, d:(await g.json()).data}; }, initData);
  console.log(JSON.stringify(saved.d));
  await page.tap('#backBtn'); await page.waitForSelector('[data-map]');
  await page.tap('[data-map]'); await page.waitForSelector('me-root me-tpc');
  await page.waitForTimeout(500);
  const bg = await page.evaluate(() => { const e=[...document.querySelectorAll('me-tpc')].find(x=>x.textContent.includes('Документы')); return e && [e.style.backgroundColor, e.style.color]; });
  console.log('REOPEN colors', JSON.stringify(bg));
  await page.tap('me-root me-tpc'); await page.tap('#mapDel'); await page.waitForSelector('#newMap');
  const left = await page.evaluate(async (d) => (await (await fetch('/api/maps',{headers:{Authorization:'tma '+d}})).json()).maps.length, initData);
  console.log('maps left', left);
  await b.close();
})();
